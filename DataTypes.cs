using System;

namespace DataTypes
{
    class Program
    {
        public static void Main(string[] args)
        {
            int MyNumberInt = 100000;
            long MyNumberLong = 15000000000L;
            float MyNumberFloat = 5.75F;
            double MyNumberDouble = 19.99D;
            bool IsTrue = true;
            bool IsFalse = false;
            char MyCharacter = 'B';
            string MyString = "Baby";
            Console.WriteLine(MyNumberInt);
            Console.WriteLine(MyNumberLong);
            Console.WriteLine(MyNumberFloat);
            Console.WriteLine(MyNumberDouble);
            Console.WriteLine(IsTrue);
            Console.WriteLine(IsFalse);
            Console.WriteLine(MyCharacter);
            Console.WriteLine(MyString);
        }
    }
}